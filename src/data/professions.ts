/**
 * Resolves a profession for the quote engine, including the broad
 * `otherProfessions` occupation list. Unlike `getProfessionBySlug`, this is
 * safe to call with any slug from `professionSelectorList` — occupations not
 * modelled as a full Profession fall back to the generic "Other Professional
 * Services" underwriting content (same questions, same rating treatment),
 * with just the name swapped in for display.
 */
export function getQuoteProfession(slug: string): Profession | undefined {
  const modelled = getProfessionBySlug(slug);
  if (modelled) return modelled;

  const other = otherProfessions.find((o) => o.slug === slug);
  if (!other) return undefined;

  const template = getProfessionBySlug("other-professional-services");
  if (!template) return undefined;

  return { ...template, slug: other.slug, name: other.name, pluralName: other.name };
}

